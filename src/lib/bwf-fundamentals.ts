export const BWF_FUNDAMENTAL_BY_ID: Record<
  FundamentalId,
  BwfFundamentalChapter
> = BWF_FUNDAMENTAL_CHAPTERS.reduce(
  (acc, ch) => {
    acc[ch.id] = ch;
    return acc;
  },
  {} as Record<FundamentalId, BwfFundamentalChapter>
);

export function getFundamentalChapter(
  id?: FundamentalId
): BwfFundamentalChapter | undefined {
  return id ? BWF_FUNDAMENTAL_BY_ID[id] : undefined;
}
